// Loaded explicitly by `tgv run pi`; no credentials or client settings are stored here.
import { randomUUID } from "node:crypto";

const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
// A TGV user token, as `tgv users token` makes one.
const userToken = /^tgvu_[A-Za-z0-9]{1,128}$/;

export default async function tgv(pi) {
  try {
    const root = new URL(process.env.TGV_PI_GATEWAY);
    if (
      root.username ||
      root.password ||
      root.search ||
      root.hash ||
      root.pathname !== "/" ||
      !["http:", "https:"].includes(root.protocol)
    )
      throw new Error("invalid root");
    // Optional: the gateway's user token, sent so calls record who made them.
    const token = process.env.TGV_USER_TOKEN || undefined;
    if (token !== undefined && !userToken.test(token))
      throw new Error("invalid user token");
    const {
      anthropicMessagesApi,
      openAICodexResponsesApi,
      openAIResponsesApi,
    } = await import("@earendil-works/pi-ai");
    configure(
      pi,
      root,
      {
        anthropicMessagesApi,
        openAICodexResponsesApi,
        openAIResponsesApi,
      },
      token,
    );
  } catch {
    // Pi normally reports extension-load errors and continues. This launcher
    // must not silently fall back to a direct provider when setup fails.
    process.stderr.write(
      "TGV: Pi integration could not load; Pi 1.0.0-compatible provider APIs and a valid TGV_USER_TOKEN, if set, are required.\n",
    );
    process.exit(1);
  }
}

export function configure(
  pi,
  root,
  { anthropicMessagesApi, openAICodexResponsesApi, openAIResponsesApi },
  token,
) {
  const providers = [
    ["anthropic", "anthropic-messages", "/anthropic", anthropicMessagesApi()],
    ["openai", "openai-responses", "/openai/v1", openAIResponsesApi()],
    [
      "openai-codex",
      "openai-codex-responses",
      "/codex",
      openAICodexResponsesApi(),
    ],
  ];
  let session;
  let run;
  const reset = (_event, ctx) => {
    session = ctx.sessionManager.getSessionId();
    run = undefined;
  };
  pi.on("session_start", reset);
  pi.on("session_switch", reset);
  pi.on("session_fork", reset);
  pi.on("agent_start", (_event, ctx) => {
    session = ctx.sessionManager.getSessionId();
    run = randomUUID();
  });
  pi.on("agent_end", () => {
    run = undefined;
  });

  for (const [provider, api, path, implementation] of providers) {
    const baseUrl = new URL(path, root).href;
    pi.registerProvider(provider, {
      baseUrl,
      api,
      // Retain Pi's catalog, auth resolution/refresh, conversion, callbacks,
      // and retry behavior. Only transport, endpoint, and attribution change.
      streamSimple(model, context, options = {}) {
        const headers = { ...options.headers };
        // A request's own session wins over ambient UI state. Background work
        // for another session must never inherit the current agent run.
        const requestSession = options.sessionId ?? session;
        headers["x-tgv-pi-session-id"] = uuid.test(requestSession ?? "")
          ? requestSession
          : null;
        headers["x-tgv-pi-turn-id"] =
          requestSession === session && run ? run : null;
        if (token !== undefined) headers["x-tgv-user-token"] = token;
        // Pi detects ChatGPT sign-in using this exact native URL, and omits
        // unsupported request fields accordingly. Redirect only the HTTP fetch
        // for OpenAI so its native serialization and error handling still apply.
        const nativeBaseUrl =
          provider === "openai" ? "https://api.openai.com/v1" : baseUrl;
        return implementation.streamSimple(
          { ...model, baseUrl: nativeBaseUrl },
          context,
          {
            ...options,
            headers,
            transport: "sse",
            ...(provider === "openai"
              ? { fetch: openAITransport(baseUrl, options.fetch) }
              : {}),
          },
        );
      },
    });
  }
}

function openAITransport(baseUrl, fetch = globalThis.fetch) {
  return (input, init) => {
    const url = new URL(input instanceof Request ? input.url : input);
    if (
      url.origin !== "https://api.openai.com" ||
      url.pathname !== "/v1/responses" ||
      url.username ||
      url.password
    ) {
      throw new Error("TGV: unexpected OpenAI inference URL");
    }
    const destination = new URL(`${baseUrl}/responses`);
    destination.search = url.search;
    // Retain SDK-generated bytes, headers, signal, and any supplied fetch hook.
    return fetch(
      input instanceof Request
        ? new Request(destination, input)
        : destination.href,
      init,
    );
  };
}
