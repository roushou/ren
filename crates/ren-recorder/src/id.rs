//! Typed identities for Ren's own units of work, and the capability that mints
//! them.
//!
//! Identities are never created from ambient randomness: a component receives
//! an [`IdSource`] and calls `generate`. Values read back from storage are
//! rebuilt with `restore`. Provider-native identifiers are separate types,
//! defined where they are parsed.

use std::{
    fmt,
    str::FromStr,
    sync::atomic::{AtomicU64, Ordering},
};
use uuid::Uuid;

/// Mints UUIDs for typed identities. Production uses the daemon's random
/// version 4 UUIDs; tests and replays use [`SequentialIds`].
pub trait IdSource: Send + Sync {
    fn next_uuid(&self) -> Uuid;
}

/// Deterministic UUIDs counting up from 1: `00000000-0000-0000-0000-000000000001`, …
#[derive(Debug)]
pub struct SequentialIds {
    next: AtomicU64,
}

impl Default for SequentialIds {
    fn default() -> Self {
        Self {
            next: AtomicU64::new(1),
        }
    }
}

impl SequentialIds {
    /// Count up from `first`, so separate sources sharing one store (a
    /// restarted test daemon) never repeat an identifier.
    pub fn starting_at(first: u64) -> Self {
        Self {
            next: AtomicU64::new(first),
        }
    }
}

impl IdSource for SequentialIds {
    fn next_uuid(&self) -> Uuid {
        Uuid::from_u128(u128::from(self.next.fetch_add(1, Ordering::Relaxed)))
    }
}

/// An identifier that did not parse. The input is not echoed.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("invalid {kind} identifier")]
pub struct InvalidId {
    kind: &'static str,
}

macro_rules! identity {
    ($(#[$meta:meta])* $name:ident as $kind:literal) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Serialize, serde::Deserialize)]
        #[serde(transparent)]
        pub struct $name(Uuid);

        impl $name {
            /// What this identity names, for error messages.
            pub const KIND: &'static str = $kind;

            /// A new identity from the given source.
            pub fn generate<S: IdSource + ?Sized>(ids: &S) -> Self {
                Self(ids.next_uuid())
            }

            /// Rebuild an identity previously generated by Ren and read back
            /// from storage.
            pub fn restore(uuid: Uuid) -> Self {
                Self(uuid)
            }

            pub fn as_uuid(self) -> Uuid {
                self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                self.0.hyphenated().fmt(f)
            }
        }

        impl FromStr for $name {
            type Err = InvalidId;

            fn from_str(value: &str) -> Result<Self, Self::Err> {
                Uuid::try_parse(value)
                    .map(Self)
                    .map_err(|_| InvalidId { kind: $kind })
            }
        }
    };
}

identity!(
    /// One client connection or exchange: an HTTP request/response, or an
    /// upgraded WebSocket.
    ChannelId as "channel"
);
identity!(
    /// One logical model invocation, carried by a channel.
    CallId as "call"
);
identity!(
    /// One upstream try of a call.
    AttemptId as "attempt"
);
identity!(
    /// Ren's grouping of calls that a client attributed to one session.
    RecordingId as "session"
);
identity!(
    /// Ren's grouping of calls that a client attributed to one turn of a session.
    TurnId as "turn"
);
identity!(
    /// One agent process Ren started and drove through its client's
    /// structured mode, from start to end. A run's calls may belong to a
    /// session; the run is not the session.
    RunId as "run"
);

#[cfg(test)]
mod tests {
    use super::{AttemptId, CallId, IdSource, InvalidId, SequentialIds};

    #[test]
    fn sequential_ids_are_deterministic_and_distinct_per_call() {
        let ids = SequentialIds::default();
        let call = CallId::generate(&ids);
        let attempt = AttemptId::generate(&ids);
        assert_eq!(call.to_string(), "00000000-0000-0000-0000-000000000001");
        assert_eq!(attempt.to_string(), "00000000-0000-0000-0000-000000000002");
    }

    #[test]
    fn identities_round_trip_through_text_and_json() {
        let source: &dyn IdSource = &SequentialIds::starting_at(0x7f3a_91c2);
        let id = AttemptId::generate(source);
        assert_eq!(id.to_string().parse::<AttemptId>(), Ok(id));
        assert_eq!(AttemptId::restore(id.as_uuid()), id);
        let json = serde_json::to_string(&id).unwrap();
        assert_eq!(json, format!("\"{id}\""));
        assert_eq!(serde_json::from_str::<AttemptId>(&json).unwrap(), id);
    }

    #[test]
    fn parse_errors_name_the_kind_without_echoing_input() {
        let error = "SECRET".parse::<CallId>().unwrap_err();
        assert_eq!(error, InvalidId { kind: CallId::KIND });
        assert_eq!(error.to_string(), "invalid call identifier");
    }
}
